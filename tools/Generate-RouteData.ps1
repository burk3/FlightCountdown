<#
.SYNOPSIS
    Generates RouteData.lua: the flown length (yards) of every direct flight
    path hop in WoW: Forever, from the client's TaxiPath/TaxiPathNode tables.

.DESCRIPTION
    Downloads the DB2 tables for the given build from wago.tools, walks each
    path's waypoints along a Catmull-Rom curve (taxis fly a smooth spline
    through their waypoints, not straight segments), and writes the lengths
    keyed by fromNodeID * 10000 + toNodeID.

    Paths that pause (boats/zeppelins), teleport, or change continent are
    skipped.

.EXAMPLE
    ./tools/Generate-RouteData.ps1 -Build 1.60.1.70938
#>
param(
    [Parameter(Mandatory)] [string] $Build,
    [string] $OutFile = (Join-Path $PSScriptRoot '..\RouteData.lua'),
    [int] $Steps = 16
)

$ErrorActionPreference = 'Stop'
$work = Join-Path ([IO.Path]::GetTempPath()) "flightcountdown-db2-$Build"
New-Item -ItemType Directory -Force $work | Out-Null

function Get-Table([string] $name) {
    $file = Join-Path $work "$name.csv"
    if (-not (Test-Path $file)) {
        Invoke-WebRequest -Uri "https://wago.tools/db2/$name/csv?build=$Build" -OutFile $file
    }
    Import-Csv $file
}

$paths = Get-Table 'TaxiPath'
$nodesByPath = Get-Table 'TaxiPathNode' | Group-Object PathID -AsHashTable -AsString

function Get-Point($row) {
    [double[]]@([double]$row.Loc_0, [double]$row.Loc_1, [double]$row.Loc_2)
}

# Uniform Catmull-Rom between p1 and p2 at parameter t.
function Get-CatmullRom([double[]]$p0, [double[]]$p1, [double[]]$p2, [double[]]$p3, [double]$t) {
    $t2 = $t * $t; $t3 = $t2 * $t
    $out = [double[]]::new(3)
    for ($i = 0; $i -lt 3; $i++) {
        $out[$i] = 0.5 * ((2 * $p1[$i]) +
            (-$p0[$i] + $p2[$i]) * $t +
            (2 * $p0[$i] - 5 * $p1[$i] + 4 * $p2[$i] - $p3[$i]) * $t2 +
            (-$p0[$i] + 3 * $p1[$i] - 3 * $p2[$i] + $p3[$i]) * $t3)
    }
    $out
}

function Get-Distance([double[]]$a, [double[]]$b) {
    [Math]::Sqrt(($a[0] - $b[0]) * ($a[0] - $b[0]) + ($a[1] - $b[1]) * ($a[1] - $b[1]) + ($a[2] - $b[2]) * ($a[2] - $b[2]))
}

$routes = [ordered]@{}
$skipped = 0

foreach ($path in ($paths | Sort-Object { [int]$_.FromTaxiNode }, { [int]$_.ToTaxiNode })) {
    $from = [int]$path.FromTaxiNode
    $to = [int]$path.ToTaxiNode
    $rows = $nodesByPath[$path.ID]
    if (-not $rows -or $from -eq $to -or $rows.Count -lt 2) { $skipped++; continue }

    $rows = $rows | Sort-Object { [int]$_.NodeIndex }
    $continents = $rows | Select-Object -ExpandProperty ContinentID -Unique
    $pauses = $rows | Where-Object { [int]$_.Delay -gt 0 -or ([int]$_.Flags -band 1) }
    if (@($continents).Count -ne 1 -or $pauses) { $skipped++; continue }

    $pts = @($rows | ForEach-Object { , (Get-Point $_) })
    $n = $pts.Count
    $length = 0.0
    for ($i = 0; $i -lt $n - 1; $i++) {
        $p0 = $pts[[Math]::Max(0, $i - 1)]
        $p1 = $pts[$i]
        $p2 = $pts[$i + 1]
        $p3 = $pts[[Math]::Min($n - 1, $i + 2)]
        $prev = $p1
        for ($s = 1; $s -le $Steps; $s++) {
            $cur = Get-CatmullRom $p0 $p1 $p2 $p3 ($s / $Steps)
            $length += Get-Distance $prev $cur
            $prev = $cur
        }
    }

    $routes[[string]($from * 10000 + $to)] = [int][Math]::Round($length)
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("-- Generated by tools/Generate-RouteData.ps1 from WoW: Forever build $Build.")
$lines.Add('-- Flown length in yards of each direct flight path hop,')
$lines.Add('-- keyed by fromTaxiNodeID * 10000 + toTaxiNodeID. Do not edit by hand.')
$lines.Add('local _, ns = ...')
$lines.Add("ns.routeDataBuild = `"$Build`"")
$lines.Add('ns.routeYards = {')
foreach ($key in $routes.Keys) { $lines.Add("    [$key] = $($routes[$key]),") }
$lines.Add('}')

[IO.File]::WriteAllLines((Resolve-Path -LiteralPath (Split-Path $OutFile) | Join-Path -ChildPath (Split-Path $OutFile -Leaf)), $lines)
Write-Host "Wrote $($routes.Count) routes ($skipped skipped) to $OutFile"
